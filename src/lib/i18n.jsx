export const LANGUAGES = [
  { code: "tr", label: "Türkçe" },
  { code: "en", label: "English" },
];

function detectLanguage() {
  if (typeof window === "undefined") return "tr";
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "tr" || saved === "en") return saved;
  } catch {
    // Storage can be unavailable in private mode; fall back to the browser language.
  }
  return String(window.navigator?.language || "").toLowerCase().startsWith("tr") ? "tr" : "en";
}

function translate(lang, key, vars) {
  const template = translations[lang]?.[key] ?? translations.tr[key] ?? key;
  if (!vars) return template;
  return String(template).replace(/\{\{(\w+)\}\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

// Head/meta helpers run outside React, so they read the saved language directly.
export function tStatic(key, vars) {
  return translate(detectLanguage(), key, vars);
}

const LangContext = createContext({
  lang: "tr",
  setLang: () => {},
  t: (key, vars) => translate("tr", key, vars),
  locale: "tr-TR",
});

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(detectLanguage);

  const setLang = useCallback((next) => {
    setLangState(next === "en" ? "en" : "tr");
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // Ignore storage failures; the language still applies for this session.
    }
  }, [lang]);

  const t = useCallback((key, vars) => translate(lang, key, vars), [lang]);

  const value = useMemo(() => ({ lang, setLang, t, locale: lang === "en" ? "en-US" : "tr-TR" }), [lang, setLang, t]);

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}
